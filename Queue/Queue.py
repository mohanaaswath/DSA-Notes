#Queue is a linear data structure that follows the First In First Out (FIFO) principle. 
#It is an abstract data type that serves as a collection of elements, with two main operations: enqueue (adding an element to the end of the queue) and dequeue (removing an element from the front of the queue). 
#Queues are commonly used in various applications such as task scheduling, breadth-first search algorithms, and managing requests in web servers.


